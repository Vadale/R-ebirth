# Run inside the installing R, after linking the package DLL. Unlike a standalone
# Rust executable this also works when R supplies its API from its executable
# instead of libR. The loaded DLL determines production/selftest registrations.
args <- commandArgs(TRUE)
stopifnot(length(args) == 2L)
dll <- dyn.load(normalizePath(args[[1L]], mustWork = TRUE), local = TRUE, now = TRUE)
symbol <- getNativeSymbolInfo("wrap__make_relm_wrappers", PACKAGE = dll)
stopifnot(identical(symbol$numParameters, 2L))
wrappers <- .Call(symbol, TRUE, "relm")
stopifnot(is.character(wrappers), length(wrappers) == 1L, !is.na(wrappers))
header <- paste0(
  "# Generated by extendr: Do not edit by hand\n# nolint start\n\n",
  "#' @usage NULL\n#' @useDynLib relm, .registration = TRUE\nNULL\n\n"
)
text <- paste0(header, wrappers, "# nolint end\n")
invisible(parse(text = text))
writeChar(text, args[[2L]], eos = NULL, useBytes = TRUE)
cat("RELM_R_HOSTED_WRAPPERS_OK\n")
