library(relm)
e<-new.env(parent=asNamespace('relm'))
sys.source('rebirth/tests/testthat/helper-llm.R',e)
sys.source('rebirth/tests/testthat/helper-graphics.R',e)
r<-testthat::test_file('rebirth/tests/testthat/test-graphics-spill.R',env=e,reporter='summary')
rows<-as.data.frame(r);out<-Sys.getenv('RELM_F6C_EVIDENCE')
write.csv(rows[,setdiff(names(rows),'result')],file.path(out,'prefix-tests.csv'),row.names=FALSE)
stopifnot(nrow(rows)==3L,all(rows$failed==0L),!any(rows$error),!any(rows$skipped),all(rows$warning==0L))
cat('F6C_PREFIX_TESTS_PASSED',sum(rows$passed),'\n')
