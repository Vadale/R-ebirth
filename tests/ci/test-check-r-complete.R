# Base R only; CI: Linux-release R-CMD-check before the package build.
source("tests/ci/check-r-complete.R")
p <- tempfile("r-check-complete-")
check_case <- function(lines, accept) {
  writeLines(lines, p, useBytes = TRUE)
  error <- tryCatch({ verify_r_check_complete(p); NULL }, error = conditionMessage)
  if (accept) stopifnot(is.null(error)) else stopifnot(!is.null(error))
}
check_case(c("* checking tests ... OK", "* DONE", "Status: OK"), TRUE)
check_case(c("* checking CRAN incoming feasibility ... NOTE", "* DONE", "Status: 1 NOTE"), TRUE)
check_case(c("* DONE", "Status: 2 NOTEs"), TRUE)
check_case(c("* DONE", "Status: 2 NOTES"), FALSE)
check_case(c("* checking tests ... OK\r", "* DONE\r", "Status: OK\r"), TRUE)
check_case(c("* using R Under development", "* checking CRAN incoming feasibility ..."), FALSE)
check_case(character(), FALSE)
check_case(c("* DONE (relm)", "Status: OK"), FALSE)
check_case("Status: OK", FALSE)
check_case(c("* DONE", "Status: 1 ERROR"), FALSE)
check_case(c("* DONE", "Status: 1 WARNING, 1 NOTE"), FALSE)
check_case(c("* DONE", "Status: UNKNOWN"), FALSE)
check_case(c("* DONE", "Status: OK", "* DONE", "Status: OK"), FALSE)
check_case(c("* DONE", "Status: OK", "Execution halted"), FALSE)
unlink(p)
stopifnot(inherits(try(verify_r_check_complete(p), silent = TRUE), "try-error"))
cat("R check completion controls: PASS (4 accepted, 11 refused; no build/model/network)\n")
